#!/usr/bin/env python3
"""
apply_niqqud.py — מחיל את מילון הניקוד על טקסט עברי לפני שליחה ל-TTS.
שימוש:
    python apply_niqqud.py "טקסט קלט"
    echo "טקסט" | python apply_niqqud.py
המילון מוגדר למטה כ-REPLACEMENTS. הוסף/ערוך שורות כאן וב-references/niqqud-dictionary.md במקביל.
ההחלפה מתבצעת על מילים שלמות בלבד (גבולות מילה) כדי לא לפגוע בהטיות.
"""
import sys, re

# מפה: מקור (לא מנוקד) -> צורה שעובדת. סדר: מהארוך לקצר כדי למנוע התנגשויות.
REPLACEMENTS = [
    ("מהחרטום", "מֵחַרְטוֹם"),
    ("החרטום", "הַחַרְטוֹם"),
    ("חרטום", "חַרְטוֹם"),
    ("מתרחצים", "מִתְרַחֲצִים"),
    ("ממתרחצים", "מִמִּתְרַחֲצִים"),
    ("כננת", "כַּנֶּנֶת"),
    ("חבל", "חֶבֶל"),
    ("שרשרת", "שַׁרְשֶׁרֶת"),
    ("מפרצים", "מִפְרָצִים"),
    ("רדיוס", "רַדְיוּס"),
    ("העוגן", "הָעֹגֶן"),
    ("עוגן", "עֹגֶן"),
    ("קרקעית", "קַרְקָעִית"),
    # "כלי השייט" ברבים — מוסר ניקוד אם הוסיפו בטעות; משאיר כפי שהוא
]

# מילים שאין לנקד — אם מופיע ניקוד עליהן, ננקה אותו
STRIP_NIQQUD_WORDS = ["כלי", "השייט"]
NIQQUD_RE = re.compile(r"[\u0591-\u05C7]")

def apply(text: str) -> str:
    for src, dst in REPLACEMENTS:
        # רק אם המילה עדיין לא מנוקדת (אין סימני ניקוד צמודים)
        text = re.sub(r"(?<![\u0591-\u05C7])" + re.escape(src) + r"(?![\u0591-\u05C7])", dst, text)
    return text

if __name__ == "__main__":
    inp = " ".join(sys.argv[1:]) if len(sys.argv) > 1 else sys.stdin.read()
    sys.stdout.write(apply(inp))
